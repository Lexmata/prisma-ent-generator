import { describe, it, expect } from 'vitest';
import { toSnakeCase, modelToFileName, fileHeader, indent } from '../utils';

describe('toSnakeCase', () => {
  it('converts camelCase to snake_case', () => {
    expect(toSnakeCase('createdAt')).toBe('created_at');
    expect(toSnakeCase('authorId')).toBe('author_id');
    expect(toSnakeCase('viewCount')).toBe('view_count');
  });

  it('converts PascalCase to snake_case', () => {
    expect(toSnakeCase('PostStatus')).toBe('post_status');
    expect(toSnakeCase('BlogPost')).toBe('blog_post');
    expect(toSnakeCase('User')).toBe('user');
  });

  it('handles consecutive uppercase letters', () => {
    expect(toSnakeCase('HTMLParser')).toBe('html_parser');
    expect(toSnakeCase('APIKey')).toBe('api_key');
  });

  it('preserves already-lowercase strings', () => {
    expect(toSnakeCase('name')).toBe('name');
    expect(toSnakeCase('posts')).toBe('posts');
    expect(toSnakeCase('email')).toBe('email');
  });

  it('handles single-character strings', () => {
    expect(toSnakeCase('A')).toBe('a');
    expect(toSnakeCase('a')).toBe('a');
  });
});

describe('modelToFileName', () => {
  it('converts model names to lowercase file names', () => {
    expect(modelToFileName('User')).toBe('user');
    expect(modelToFileName('BlogPost')).toBe('blog_post');
    expect(modelToFileName('Tag')).toBe('tag');
    expect(modelToFileName('PostStatus')).toBe('post_status');
  });
});

describe('fileHeader', () => {
  it('returns the auto-generated header comment', () => {
    const header = fileHeader();
    expect(header).toContain('Code generated by prisma-ent-generator');
    expect(header).toContain('DO NOT EDIT');
  });
});

describe('indent', () => {
  it('indents with one tab by default', () => {
    expect(indent('hello')).toBe('\thello');
  });

  it('indents with multiple tabs', () => {
    expect(indent('hello', 2)).toBe('\t\thello');
  });

  it('preserves empty lines without indentation', () => {
    expect(indent('a\n\nb', 1)).toBe('\ta\n\n\tb');
  });
});
