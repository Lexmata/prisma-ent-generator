import { describe, it, expect } from 'vitest';
import type { DMMF } from '@prisma/generator-helper';
import { generateSchema } from '../helpers/schema';

/**
 * Helper to create a minimal DMMF.Field for testing.
 */
function makeField(overrides: Partial<DMMF.Field>): DMMF.Field {
  return {
    name: 'testField',
    kind: 'scalar',
    isList: false,
    isRequired: true,
    isUnique: false,
    isId: false,
    isReadOnly: false,
    isGenerated: false,
    isUpdatedAt: false,
    type: 'String',
    hasDefaultValue: false,
    ...overrides,
  } as DMMF.Field;
}

function makeModel(name: string, fields: DMMF.Field[], documentation?: string): DMMF.Model {
  return {
    name,
    fields,
    uniqueFields: [],
    uniqueIndexes: [],
    primaryKey: null,
    dbName: null,
    documentation,
  } as unknown as DMMF.Model;
}

describe('generateSchema', () => {
  it('generates a complete Go schema file for a simple model', () => {
    const model = makeModel('Tag', [
      makeField({
        name: 'id',
        type: 'Int',
        isId: true,
        hasDefaultValue: true,
        default: { name: 'autoincrement', args: [] },
      }),
      makeField({ name: 'name', type: 'String', isUnique: true }),
    ]);

    const output = generateSchema(model, [model], new Map());

    expect(output).toContain('package schema');
    expect(output).toContain('Code generated by prisma-ent-generator');
    expect(output).toContain('type Tag struct {');
    expect(output).toContain('ent.Schema');
    expect(output).toContain('func (Tag) Fields() []ent.Field {');
    expect(output).toContain('field.String("name").Unique()');
    expect(output).toContain('func (Tag) Edges() []ent.Edge {');
    expect(output).toContain('return nil'); // no edges
  });

  it('includes documentation as Go comments', () => {
    const model = makeModel('User', [
      makeField({
        name: 'id',
        type: 'Int',
        isId: true,
        hasDefaultValue: true,
        default: { name: 'autoincrement', args: [] },
      }),
    ], 'A user in the system');

    const output = generateSchema(model, [model], new Map());
    expect(output).toContain('// User A user in the system');
  });

  it('prefixes all lines of multi-line documentation with //', () => {
    const doc = 'Stores per-firm API credentials. apiKeyEncrypted uses AES-256-GCM\nwith a key sourced from AWS SSM Parameter Store.';
    const model = makeModel('Connection', [
      makeField({
        name: 'id',
        type: 'Int',
        isId: true,
        hasDefaultValue: true,
        default: { name: 'autoincrement', args: [] },
      }),
    ], doc);

    const output = generateSchema(model, [model], new Map());
    expect(output).toContain('// Connection Stores per-firm API credentials. apiKeyEncrypted uses AES-256-GCM');
    expect(output).toContain('// with a key sourced from AWS SSM Parameter Store.');
    expect(output).not.toMatch(/\n[^/\n][^/][^\n]*\ntype Connection/);
  });

  it('handles empty lines in multi-line documentation', () => {
    const doc = 'First line.\n\nThird line after blank.';
    const model = makeModel('Widget', [
      makeField({
        name: 'id',
        type: 'Int',
        isId: true,
        hasDefaultValue: true,
        default: { name: 'autoincrement', args: [] },
      }),
    ], doc);

    const output = generateSchema(model, [model], new Map());
    expect(output).toContain('// Widget First line.');
    expect(output).toContain('//\n// Third line after blank.');
  });

  it('generates imports based on field types', () => {
    const model = makeModel('Event', [
      makeField({
        name: 'id',
        type: 'Int',
        isId: true,
        hasDefaultValue: true,
        default: { name: 'autoincrement', args: [] },
      }),
      makeField({
        name: 'startAt',
        type: 'DateTime',
        hasDefaultValue: true,
        default: { name: 'now', args: [] },
      }),
    ]);

    const output = generateSchema(model, [model], new Map());
    expect(output).toContain('"time"');
    expect(output).toContain('"entgo.io/ent/schema/field"');
  });

  it('generates edge imports when relations exist', () => {
    const userModel = makeModel('User', [
      makeField({
        name: 'id',
        type: 'Int',
        isId: true,
        hasDefaultValue: true,
        default: { name: 'autoincrement', args: [] },
      }),
      makeField({
        name: 'posts',
        kind: 'object',
        type: 'Post',
        isList: true,
        relationName: 'UserPosts',
        relationFromFields: [],
        relationToFields: [],
      }),
    ]);

    const postModel = makeModel('Post', [
      makeField({
        name: 'id',
        type: 'Int',
        isId: true,
        hasDefaultValue: true,
        default: { name: 'autoincrement', args: [] },
      }),
      makeField({
        name: 'author',
        kind: 'object',
        type: 'User',
        isList: false,
        isRequired: true,
        relationName: 'UserPosts',
        relationFromFields: ['authorId'],
        relationToFields: ['id'],
      }),
    ]);

    const userOutput = generateSchema(userModel, [userModel, postModel], new Map());
    expect(userOutput).toContain('"entgo.io/ent/schema/edge"');
    expect(userOutput).toContain('edge.To("posts", Post.Type)');
  });

  it('generates a full User schema with fields and edges', () => {
    const roleEnum: DMMF.DatamodelEnum = {
      name: 'Role',
      values: [
        { name: 'USER', dbName: null },
        { name: 'ADMIN', dbName: null },
        { name: 'MODERATOR', dbName: null },
      ],
    };
    const enumDefs = new Map([['Role', roleEnum]]);

    const userModel = makeModel('User', [
      makeField({
        name: 'id',
        type: 'Int',
        isId: true,
        hasDefaultValue: true,
        default: { name: 'autoincrement', args: [] },
      }),
      makeField({ name: 'email', type: 'String', isUnique: true }),
      makeField({ name: 'name', type: 'String', isRequired: false }),
      makeField({
        name: 'role',
        kind: 'enum',
        type: 'Role',
        hasDefaultValue: true,
        default: 'USER',
      }),
      makeField({
        name: 'posts',
        kind: 'object',
        type: 'Post',
        isList: true,
        relationName: 'UserPosts',
        relationFromFields: [],
        relationToFields: [],
      }),
      makeField({
        name: 'createdAt',
        type: 'DateTime',
        hasDefaultValue: true,
        default: { name: 'now', args: [] },
      }),
      makeField({
        name: 'updatedAt',
        type: 'DateTime',
        isUpdatedAt: true,
      }),
    ]);

    const postModel = makeModel('Post', [
      makeField({
        name: 'author',
        kind: 'object',
        type: 'User',
        isList: false,
        isRequired: true,
        relationName: 'UserPosts',
        relationFromFields: ['authorId'],
        relationToFields: ['id'],
      }),
    ]);

    const output = generateSchema(userModel, [userModel, postModel], enumDefs);

    // Struct
    expect(output).toContain('type User struct {');

    // Fields
    expect(output).toContain('field.String("email").Unique()');
    expect(output).toContain('field.String("name").Optional()');
    expect(output).toContain('field.Enum("role").Values("USER", "ADMIN", "MODERATOR").Default("USER")');
    expect(output).toContain('field.Time("createdAt").Default(time.Now)');
    expect(output).toContain('field.Time("updatedAt").Default(time.Now).UpdateDefault(time.Now)');

    // Edges
    expect(output).toContain('edge.To("posts", Post.Type)');

    // Imports
    expect(output).toContain('"time"');
    expect(output).toContain('"entgo.io/ent/schema/field"');
    expect(output).toContain('"entgo.io/ent/schema/edge"');
  });
});
