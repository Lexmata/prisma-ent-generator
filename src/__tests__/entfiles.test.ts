import { describe, it, expect } from 'vitest';
import { generateGenerateGo, generateEntcGo } from '../helpers/entfiles';

describe('generateGenerateGo', () => {
  const output = generateGenerateGo();

  it('declares package ent', () => {
    expect(output).toContain('package ent');
  });

  it('includes the go:generate directive', () => {
    expect(output).toContain('//go:generate go run entgo.io/ent/cmd/ent generate ./schema');
  });

  it('includes the generated file header', () => {
    expect(output).toContain('Code generated by prisma-ent-generator');
    expect(output).toContain('DO NOT EDIT');
  });
});

describe('generateEntcGo', () => {
  const output = generateEntcGo();

  it('includes the ignore build tag', () => {
    expect(output).toContain('//go:build ignore');
  });

  it('declares package main', () => {
    expect(output).toContain('package main');
  });

  it('imports entc and gen packages', () => {
    expect(output).toContain('"entgo.io/ent/entc"');
    expect(output).toContain('"entgo.io/ent/entc/gen"');
  });

  it('calls entc.Generate with schema path', () => {
    expect(output).toContain('entc.Generate("./schema"');
  });

  it('includes error handling with log.Fatalf', () => {
    expect(output).toContain('log.Fatalf');
  });

  it('includes the generated file header', () => {
    expect(output).toContain('Code generated by prisma-ent-generator');
  });
});
