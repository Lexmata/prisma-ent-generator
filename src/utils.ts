/**
 * Convert a camelCase or PascalCase string to snake_case.
 *
 * @example
 * toSnakeCase("createdAt") // "created_at"
 * toSnakeCase("PostStatus") // "post_status"
 * toSnakeCase("authorId") // "author_id"
 */
export function toSnakeCase(str: string): string {
  return str
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1_$2')
    .toLowerCase();
}

/**
 * Convert a PascalCase model name to a lowercase file name for Go files.
 *
 * @example
 * modelToFileName("User") // "user"
 * modelToFileName("BlogPost") // "blog_post"
 */
export function modelToFileName(modelName: string): string {
  return toSnakeCase(modelName);
}

/**
 * Generate a Go file header comment indicating the file is auto-generated.
 */
export function fileHeader(): string {
  return [
    '// Code generated by prisma-ent-generator. DO NOT EDIT.',
    '',
  ].join('\n');
}

/**
 * Indent each line of a string by a given number of tabs.
 */
export function indent(str: string, tabs: number = 1): string {
  const prefix = '\t'.repeat(tabs);
  return str
    .split('\n')
    .map((line) => (line.trim() ? prefix + line : line))
    .join('\n');
}
